// Writes the names of the externs that the runtime implements on each target to
// `src/LeanScript/TargetExterns.lean`, for the compiler to check programs against. Each target's
// runtime is loaded under its export conditions, as a program on that target would load it.
//
// With `--check`, instead fails if that file is out of date.
//
// Usage: node scripts/gen-target-externs.js [--check]

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const output = join(root, "src", "LeanScript", "TargetExterns.lean");
const runtimeUrl = new URL("../src/runtime/index.js", import.meta.url).href;

/** The export conditions of each target, and the name of its Lean definition. */
const targets = [
  { conditions: [], def: "nodeExterns", platform: "Node" },
  { conditions: ["browser"], def: "browserExterns", platform: "browsers" },
];

const quoteLean = (s) => s.replaceAll("\\", "\\\\").replaceAll('"', '\\"');

function externNames(conditions) {
  const script = `const { externs } = await import(${JSON.stringify(runtimeUrl)});
console.log(Object.keys(externs).sort().join("\\n"));`;
  const stdout = execFileSync(
    process.execPath,
    [...conditions.map((c) => `--conditions=${c}`), "--input-type=module", "--eval", script],
    { encoding: "utf8" },
  );
  return stdout.trimEnd().split("\n");
}

let contents = `-- Generated by \`scripts/gen-target-externs.js\` from the runtime. Do not edit.

namespace LeanScript
`;
for (const { conditions, def, platform } of targets) {
  const names = externNames(conditions).map(quoteLean).join("\n");
  contents += `
/-- The names of the externs that the runtime implements on ${platform}, one per line. -/
def ${def} : String := "${names}"
`;
}

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== contents) {
    console.error(`${output} is out of date; run \`node scripts/gen-target-externs.js\``);
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, contents);
}
