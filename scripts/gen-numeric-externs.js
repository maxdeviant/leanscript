// Writes the externs of the fixed-width integers and floats to `externs/fixed.js` and
// `externs/float.js` in the runtime.
//
// These types have the same operations with small differences, so their externs are generated. Each
// extern is written out as a separate function, as a bundler can't remove the unused results of
// functions that build externs at startup.
//
// With `--check`, instead fails if those files are out of date.
//
// Usage: node scripts/gen-numeric-externs.js [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import prettier from "prettier";

const root = join(import.meta.dirname, "..");
const externsDir = join(root, "packages", "runtime", "src", "externs");

const header = (name) => `// Generated by \`scripts/gen-numeric-externs.js\`. Do not edit.
//
// The externs of \`${name}.js\`.
`;

/** Collects the statements of a module of externs. */
class Module {
  statements = [];

  /** Adds the extern `key`, whose implementation takes `params` and returns the expression `body`. */
  extern(key, params, body) {
    const local = key.replaceAll(".", "_");
    this.statements.push(`const ${local} = (${params}) => ${body};
export { ${local} as "${key}" };`);
  }

  /** Adds the extern `key`, whose implementation is `local`. */
  alias(key, local) {
    this.statements.push(`export { ${local} as "${key}" };`);
  }
}

/** A fixed-width integer type that is represented as a JS number. */
function smallType(name, width, signed) {
  const mask = width === 32 ? null : (1 << width) - 1;
  const shift = 32 - width;
  const toSigned = (a) => (width === 32 ? `(${a} | 0)` : `((${a} << ${shift}) >> ${shift})`);
  const value = signed ? toSigned : (a) => a;
  const wrap = (n) => (width === 32 ? `((${n}) >>> 0)` : `((${n}) & ${mask})`);
  const amount = `(b & ${width - 1})`;
  return {
    name,
    signed,
    big: false,
    wrap,
    value,
    toInteger: value,
    zero: "0",
    // The first `>>> 0` is redundant, but `nat_repr` runs about 20% slower in Chrome without it,
    // even if `USize.ofNatLT` returns `n` directly. This is likely a V8 inlining decision.
    ofInteger: `(n) =>
      typeof n === "number" && n >= -0x80000000 && n <= 0xffffffff
        ? ${wrap("n >>> 0")}
        : Number(BigInt.asUintN(${width}, BigInt(n)))`,
    mul: width === 32 ? "Math.imul(a, b) >>> 0" : wrap("a * b"),
    div: wrap(`Math.trunc(${value("a")} / ${value("b")})`),
    rem: wrap(`${value("a")} % ${value("b")}`),
    land: wrap("a & b"),
    lor: wrap("a | b"),
    xor: wrap("a ^ b"),
    // The width is a power of two, so the low bits of `b` are its remainder modulo the width whether
    // `b` is read as unsigned or as signed (as `BitVec.smod` does for the signed types).
    shiftLeft: wrap(`a << ${amount}`),
    shiftRight: signed ? wrap(`${toSigned("a")} >> ${amount}`) : `a >>> ${amount}`,
    log2: "a === 0 ? 0 : 31 - Math.clz32(a)",
    abs: wrap(`Math.abs(${toSigned("a")})`),
    toFloat: value("a"),
  };
}

/** A fixed-width integer type that is represented as a `BigInt`. */
function bigType(name, signed) {
  const toSigned = (a) => `BigInt.asIntN(64, ${a})`;
  const value = signed ? toSigned : (a) => a;
  const wrap = (n) => `BigInt.asUintN(64, ${n})`;
  const amount = "(low32(b) & 63)";
  return {
    name,
    signed,
    big: true,
    wrap,
    value,
    toInteger: signed ? (a) => `normalize(${toSigned(a)})` : (a) => `normalize(${a})`,
    zero: "0n",
    ofInteger: `(n) => ${wrap("BigInt(n)")}`,
    mul: wrap("a * b"),
    div: wrap(`${value("a")} / ${value("b")}`),
    rem: wrap(`${value("a")} % ${value("b")}`),
    land: "a & b",
    lor: "a | b",
    xor: "a ^ b",
    shiftLeft: wrap(`a << BigInt${amount}`),
    shiftRight: signed ? wrap(`${toSigned("a")} >> BigInt${amount}`) : `shiftRight64(a, ${amount})`,
    log2: "a === 0n ? 0n : BigInt(a.toString(2).length - 1)",
    abs: wrap(`${toSigned("a")} < 0n ? -${toSigned("a")} : a`),
    toFloat: `Number(${value("a")})`,
  };
}

const fixedTypes = [
  smallType("UInt8", 8, false),
  smallType("UInt16", 16, false),
  smallType("UInt32", 32, false),
  bigType("UInt64", false),
  smallType("USize", 32, false),
  smallType("Int8", 8, true),
  smallType("Int16", 16, true),
  smallType("Int32", 32, true),
  bigType("Int64", true),
  smallType("ISize", 32, true),
];

function fixedModule() {
  const m = new Module();
  for (const t of fixedTypes) {
    m.statements.push(`const ${t.name}_ofInteger = ${t.ofInteger};`);
  }
  for (const t of fixedTypes) {
    const { name, value, wrap, zero } = t;
    const key = (op) => `${name}.${op}`;
    m.extern(key("add"), "a, b", wrap("a + b"));
    m.extern(key("sub"), "a, b", wrap("a - b"));
    m.extern(key("mul"), "a, b", t.mul);
    // Division by zero is zero, and the remainder of division by zero is the dividend.
    m.extern(key("div"), "a, b", `b === ${zero} ? ${zero} : ${t.div}`);
    m.extern(key("mod"), "a, b", `b === ${zero} ? a : ${t.rem}`);
    m.extern(key("land"), "a, b", t.land);
    m.extern(key("lor"), "a, b", t.lor);
    m.extern(key("xor"), "a, b", t.xor);
    m.extern(key("complement"), "a", wrap("~a"));
    m.extern(key("neg"), "a", wrap(`${zero} - a`));
    m.extern(key("shiftLeft"), "a, b", t.shiftLeft);
    m.extern(key("shiftRight"), "a, b", t.shiftRight);
    m.extern(key("decEq"), "a, b", "a === b ? 1 : 0");
    m.extern(key("decLt"), "a, b", `${value("a")} < ${value("b")} ? 1 : 0`);
    m.extern(key("decLe"), "a, b", `${value("a")} <= ${value("b")} ? 1 : 0`);
    m.alias(key("ofNat"), `${name}_ofInteger`);
    m.extern(key("toFloat"), "a", t.toFloat);
    m.extern(key("toFloat32"), "a", `Math.fround(${t.toFloat})`);
    if (t.signed) {
      m.alias(key("ofInt"), `${name}_ofInteger`);
      m.extern(key("toInt"), "a", t.toInteger("a"));
      m.extern(key("abs"), "a", t.abs);
    } else {
      m.extern(key("ofNatLT"), "n, _h", `${name}_ofInteger(n)`);
      m.alias(key("ofBitVec"), `${name}_ofInteger`);
      m.extern(key("toBitVec"), "a", "normalize(BigInt(a))");
      m.extern(key("toNat"), "a", t.toInteger("a"));
      m.extern(key("log2"), "a", t.log2);
    }
    // Only conversions between types of the same signedness are externs. They sign-extend from a
    // signed type and zero-extend from an unsigned one.
    for (const target of fixedTypes) {
      if (target !== t && target.signed === t.signed) {
        m.extern(
          key(`to${target.name}`),
          "a",
          // Truncating keeps only the low bits, which are the same for the signed and unsigned types.
          t.big && !target.big
            ? target.wrap("low32(a)")
            : `${target.name}_ofInteger(${t.toInteger("a")})`,
        );
      }
    }
  }
  m.extern("USize.ofNat32", "n, _h", "n");
  m.extern("USize.repr", "n", "mkString(String(n))");
  m.extern("System.Platform.getNumBits", "_unit", "32");
  return `${header("fixed")}
import { low32, shiftRight64 } from "../fixed.js";
import { normalize } from "../nat.js";
import { mkString } from "../string.js";

// As in the C runtime, a signed integer is stored as the unsigned integer with the same bits (see
// \`fixed.js\`), so the signed operations convert their arguments first.

${m.statements.join("\n\n")}
`;
}

/** Adds the externs of `Float` or `Float32`, where `round` rounds an exact or double-precision result. */
function addFloatExterns(m, name, round, ofBits, toBits) {
  const key = (op) => `${name}.${op}`;
  const unary = (op, body) => m.extern(key(op), "a", round(body));
  m.extern(key("ofBits"), "b", `${ofBits}(b)`);
  // The bit-level model of an IEEE 754 float is its bit pattern.
  m.extern(key("ofModel"), "b", `${ofBits}(b)`);
  m.extern(key("toBits"), "x", `${toBits}(x)`);
  m.extern(key("toModel"), "x", `${toBits}(x)`);
  m.extern(key("add"), "a, b", round("a + b"));
  m.extern(key("sub"), "a, b", round("a - b"));
  m.extern(key("mul"), "a, b", round("a * b"));
  m.extern(key("div"), "a, b", round("a / b"));
  m.extern(key("neg"), "a", "-a");
  m.extern(key("abs"), "a", "Math.abs(a)");
  m.extern(key("decLt"), "a, b", "a < b ? 1 : 0");
  m.extern(key("decLe"), "a, b", "a <= b ? 1 : 0");
  m.extern(key("lt"), "a, b", "a < b ? 1 : 0");
  m.extern(key("le"), "a, b", "a <= b ? 1 : 0");
  m.extern(key("beq"), "a, b", "a === b ? 1 : 0");
  m.extern(key("isNaN"), "a", "Number.isNaN(a) ? 1 : 0");
  m.extern(key("isFinite"), "a", "Number.isFinite(a) ? 1 : 0");
  m.extern(key("isInf"), "a", "a === Infinity || a === -Infinity ? 1 : 0");
  m.extern(key("toString"), "x", "mkString(floatToString(x))");
  for (const op of ["sin", "cos", "tan", "asin", "acos", "atan"]) {
    unary(op, `Math.${op}(a)`);
  }
  m.extern(key("atan2"), "a, b", round("Math.atan2(a, b)"));
  for (const op of ["sinh", "cosh", "tanh", "asinh", "acosh", "atanh", "exp"]) {
    unary(op, `Math.${op}(a)`);
  }
  unary("exp2", "2 ** a");
  for (const op of ["log", "log2", "log10"]) {
    unary(op, `Math.${op}(a)`);
  }
  m.extern(key("pow"), "a, b", round("a ** b"));
  unary("sqrt", "Math.sqrt(a)");
  unary("cbrt", "Math.cbrt(a)");
  m.extern(key("ceil"), "a", "Math.ceil(a)");
  m.extern(key("floor"), "a", "Math.floor(a)");
  m.extern(key("round"), "a", "roundHalfAway(a)");
  m.extern(key("fma"), "a, b, c", round("fma(a, b, c)"));
  m.extern(key("scaleB"), "a, n", round("scalbn(a, clampExponent(n))"));
  m.extern(key("frExp"), "a", "mkCtor(0, frexp(a), null)");
  m.extern(key("toUInt8"), "a", "toUnsigned(a, 0xff)");
  m.extern(key("toUInt16"), "a", "toUnsigned(a, 0xffff)");
  m.extern(key("toUInt32"), "a", "toUnsigned(a, 0xffffffff)");
  m.extern(key("toUInt64"), "a", "toUInt64(a)");
  m.extern(key("toUSize"), "a", "toUnsigned(a, 0xffffffff)");
  m.extern(key("toInt8"), "a", "toSigned(a, 8)");
  m.extern(key("toInt16"), "a", "toSigned(a, 16)");
  m.extern(key("toInt32"), "a", "toSigned(a, 32)");
  m.extern(key("toInt64"), "a", "toInt64(a)");
  m.extern(key("toISize"), "a", "toSigned(a, 32)");
}

function floatModule() {
  const m = new Module();
  addFloatExterns(m, "Float", (x) => x, "floatOfBits", "floatToBits");
  addFloatExterns(m, "Float32", (x) => `Math.fround(${x})`, "float32OfBits", "float32ToBits");
  m.extern("Float.toFloat32", "a", "Math.fround(a)");
  m.extern("Float32.toFloat", "a", "a");
  return `${header("float")}
import { mkCtor } from "../core.js";
import {
  clampExponent,
  float32OfBits,
  float32ToBits,
  floatOfBits,
  floatToBits,
  floatToString,
  fma,
  frexp,
  roundHalfAway,
  scalbn,
  toInt64,
  toSigned,
  toUInt64,
  toUnsigned,
} from "../float.js";
import { mkString } from "../string.js";

${m.statements.join("\n\n")}
`;
}

const outputs = [
  [join(externsDir, "fixed.js"), fixedModule()],
  [join(externsDir, "float.js"), floatModule()],
];

for (const [path, source] of outputs) {
  const options = await prettier.resolveConfig(path);
  const contents = await prettier.format(source, { ...options, filepath: path });
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== contents) {
      console.error(`${path} is out of date; run \`node scripts/gen-numeric-externs.js\``);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, contents);
  }
}
